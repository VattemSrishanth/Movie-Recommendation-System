"""
train_model.py
--------------
Load a multilingual TMDB dataset and train a content-based recommendation model
using genres, keywords, and overview text. The script computes cosine
similarity and stores the processed data for the Flask app.

Usage:
    python train_model.py
"""

import os
import pickle

import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

# ── paths ────────────────────────────────────────────────────────────────
BASE_DIR = os.path.dirname(__file__)
DATASET_DIR = os.path.join(BASE_DIR, "dataset")
MODEL_DIR = os.path.join(BASE_DIR, "model")
MODEL_PATH = os.path.join(MODEL_DIR, "recommendation_model.pkl")
DATA_PATH = os.path.join(DATASET_DIR, "tmdb_movies.csv")


def load_data() -> pd.DataFrame:
    """Load the multilingual TMDB dataset generated by download_dataset.py."""
    if not os.path.exists(DATA_PATH):
        raise FileNotFoundError(
            "TMDB dataset not found. Run download_dataset.py after setting TMDB_API_KEY."
        )

    movies = pd.read_csv(DATA_PATH)
    print(f"Loaded {len(movies)} multilingual TMDB movies from {DATA_PATH}")
    return movies


def preprocess(movies: pd.DataFrame) -> pd.DataFrame:
    """
    Clean the TMDB data and build the text feature used by TF-IDF.

    The content field combines genres, keywords, and overview so the model can
    match movies by category, subject matter, and plot-level semantics.
    """
    movies = movies.copy()
    movies = movies.dropna(subset=["title", "genres"]).copy()
    movies["genres"] = movies["genres"].fillna("")
    movies["keywords"] = movies["keywords"].fillna("")
    movies["overview"] = movies["overview"].fillna("")
    movies["poster_url"] = movies["poster_url"].fillna("")
    movies["year"] = movies["year"].fillna("")
    movies["vote_average"] = movies["vote_average"].fillna(0.0)
    movies["vote_count"] = movies["vote_count"].fillna(0).astype(int)
    movies["popularity"] = movies["popularity"].fillna(0.0)

    # Replace separators so TF-IDF can learn meaningful word tokens.
    movies["genres_text"] = movies["genres"].str.replace("|", " ", regex=False)
    movies["keywords_text"] = movies["keywords"].str.replace("_", " ", regex=False)

    movies["content"] = (
        movies["genres_text"] + " " + movies["keywords_text"] + " " + movies["overview"]
    ).str.lower().str.replace(r"\s+", " ", regex=True).str.strip()

    movies = movies[movies["content"] != ""]

    movies.reset_index(drop=True, inplace=True)
    print(f"After cleaning: {len(movies)} movies remain")
    return movies


def build_similarity_matrix(movies: pd.DataFrame):
    """
    Vectorise the combined content with TF-IDF and compute pairwise cosine similarity.

    TF-IDF (Term Frequency – Inverse Document Frequency) converts text into
    numerical feature vectors.  Cosine similarity then measures how close
    two vectors are, giving a value between 0 (completely different) and 1
    (identical).  Movies that share genres, themes, and plot vocabulary will
    have high similarity.
    """
    tfidf = TfidfVectorizer(stop_words="english", ngram_range=(1, 2), max_features=15000)
    tfidf_matrix = tfidf.fit_transform(movies["content"])
    print(f"TF-IDF matrix shape: {tfidf_matrix.shape}")

    # Cosine similarity between every pair of movies
    similarity = cosine_similarity(tfidf_matrix, tfidf_matrix)
    print(f"Similarity matrix shape: {similarity.shape}")
    return similarity


def save_model(movies: pd.DataFrame, similarity):
    """Persist the movie list and similarity matrix to a pickle file."""
    os.makedirs(MODEL_DIR, exist_ok=True)

    model_data = {
        "movies": movies,
        "similarity": similarity,
    }

    with open(MODEL_PATH, "wb") as f:
        pickle.dump(model_data, f)

    size_mb = os.path.getsize(MODEL_PATH) / (1024 * 1024)
    print(f"Model saved to {MODEL_PATH}  ({size_mb:.1f} MB)")


def main():
    print("=" * 50)
    print("  Training Movie Recommendation Model")
    print("=" * 50)

    movies = load_data()
    movies = preprocess(movies)
    similarity = build_similarity_matrix(movies)
    save_model(movies, similarity)

    print("\nDone!  You can now run the Flask app with:  python app.py")


if __name__ == "__main__":
    main()
